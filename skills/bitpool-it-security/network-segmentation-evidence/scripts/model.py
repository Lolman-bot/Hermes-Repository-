"""Normalise raw AWS CLI dumps into one model.

v1.1 changes:
  * reads the collection manifest for provenance instead of guessing from file mtime
  * every (profile, region) pair is modelled, not just the primary region
  * load balancers are resolved per account AND region, so exposure scope is
    correct outside aws-prod (v1.0 silently mislabelled these)
  * transit gateway attachments and VPC endpoints are modelled
  * egress rules are analysed, not only ingress
"""
import json
import os

SENSITIVE = {22: "SSH", 3389: "RDP", 3306: "MySQL", 5432: "PostgreSQL", 5433: "PostgreSQL",
             27017: "MongoDB", 6379: "Redis", 1433: "MSSQL", 9200: "Elasticsearch",
             11211: "memcached", 2375: "Docker", 9300: "Elasticsearch"}


def _tag(tags, key="Name"):
    for t in (tags or []):
        if t.get("Key") == key:
            return t.get("Value")
    return ""


class Dump:
    """Reads {profile}__{region}__{kind}.json plus _manifest.json."""

    def __init__(self, base):
        self.base = base
        self.manifest = self._load_raw("_manifest.json") or {}

    def _load_raw(self, name):
        try:
            with open(os.path.join(self.base, name), encoding="utf-8-sig") as fh:
                return json.load(fh)
        except Exception:
            return None

    def load(self, profile, region, kind):
        return self._load_raw(f"{profile}__{region}__{kind}.json") or {}

    def pairs(self):
        rows = self.manifest.get("regions_with_vpcs") or []
        return [(r["profile"], r["region"]) for r in rows]


def subnet_tier(rtb):
    """Derive the real tier from the route table, never from the Name tag."""
    if rtb is None:
        return "unrouted"
    for r in rtb.get("Routes", []):
        if r.get("DestinationCidrBlock") == "0.0.0.0/0":
            gw = r.get("GatewayId") or ""
            if gw.startswith("igw-"):
                return "public"
            if r.get("NatGatewayId") or gw.startswith("nat-"):
                return "private"
    return "isolated"


def provenance_footer(p):
    """The `## Source` block every generated Markdown deliverable ends with.

    Defined once because more than one module emits it and it has already drifted:
    the file count was reconciled against the dump in the HTML card and left bare
    in both Markdown footers, so two of three deliverables stated a number that did
    not match the zip shipped beside them. Any change to provenance wording belongs
    here and nowhere else — if you find yourself retyping this sentence, import it.
    """
    return (
        "## Source\n\n"
        "Generated by the `/network-segmentation-evidence` skill from a read-only sweep.\n"
        f"Collected {p.get('collected_utc')} · dump digest `{p.get('digest')}` · "
        f"{p.get('files')} files hashed — the dump holds {p.get('files_in_zip')}, "
        "the extra being `_manifest.json`, which carries the digest and so is not "
        "covered by it.\n"
        "Re-run the skill to refresh; do not edit this file by hand.\n"
    )


def _open_rules(sg, direction):
    """Rules in this group open to the whole internet, by direction."""
    perms = sg.get("IpPermissions" if direction == "ingress" else "IpPermissionsEgress", [])
    out = []
    for perm in perms:
        wide = any(r.get("CidrIp") == "0.0.0.0/0" for r in perm.get("IpRanges", [])) \
            or any(r.get("CidrIpv6") == "::/0" for r in perm.get("Ipv6Ranges", []))
        if not wide:
            continue
        fr, to, proto = perm.get("FromPort"), perm.get("ToPort"), perm.get("IpProtocol")
        if proto == "-1":
            out.append({"port": "all protocols", "services": ["ALL"], "all": True})
            continue
        names = sorted({SENSITIVE[k] for k in SENSITIVE
                        if fr is not None and to is not None and fr <= k <= to})
        label = f"{proto}/{fr}" if fr == to else f"{proto}/{fr}-{to}"
        out.append({"port": label, "services": names, "all": False})
    return out


def build(base):
    d = Dump(base)
    mf = d.manifest
    prof_to_acct = mf.get("profiles") or {}
    org = {a["Id"]: a.get("Name", "") for a in (mf.get("org_accounts") or [])}

    model = {
        "provenance": {
            "generator": mf.get("generator", "netpack"),
            "collected_utc": mf.get("collected_utc"),
            "collected_by": mf.get("collected_by"),
            "digest": mf.get("dump_digest"),
            "files": mf.get("file_count"),
            # The manifest carries the digest, so it cannot be inside the set the
            # digest covers. The zip therefore always holds one more file than the
            # count that was hashed. Both numbers are carried because a bare count
            # next to a digest reads as a count of the zip, and it is not.
            "files_in_zip": (mf.get("file_count") or 0) + 1,
        },
        "regions_enabled": mf.get("regions_enabled") or [],
        "regions_with_vpcs": sorted({r["region"] for r in (mf.get("regions_with_vpcs") or [])}),
        "org_account_count": len(org),
        "uncovered_accounts": mf.get("uncovered_accounts") or [],
        "excluded_accounts": mf.get("excluded_accounts") or [],
        "accounts": [], "peerings": [],
    }

    by_profile = {}
    for prof, region in d.pairs():
        vpcs = d.load(prof, region, "vpcs").get("Vpcs", [])
        subs = d.load(prof, region, "subnets").get("Subnets", [])
        rtbs = d.load(prof, region, "rtb").get("RouteTables", [])
        enis = d.load(prof, region, "eni").get("NetworkInterfaces", [])
        sgs = d.load(prof, region, "sg").get("SecurityGroups", [])
        acls = d.load(prof, region, "nacl").get("NetworkAcls", [])
        fls = d.load(prof, region, "flowlogs").get("FlowLogs", [])
        eps = d.load(prof, region, "endpoints").get("VpcEndpoints", [])
        tgws = d.load(prof, region, "tgw").get("TransitGatewayAttachments", [])
        lbs = d.load(prof, region, "elbv2").get("LoadBalancers", [])

        # FIX: load balancers resolved for THIS account and region
        lb_by_sg = {}
        for lb in lbs:
            for g in (lb.get("SecurityGroups") or []):
                lb_by_sg.setdefault(g, []).append(lb)

        explicit, main = {}, {}
        for rt in rtbs:
            for a in rt.get("Associations", []):
                if a.get("SubnetId"):
                    explicit[a["SubnetId"]] = rt
                elif a.get("Main"):
                    main[rt["VpcId"]] = rt

        eni_count, eni_types, vpn_by_vpc = {}, {}, {}
        for e in enis:
            v = e.get("VpcId")
            eni_count[v] = eni_count.get(v, 0) + 1
            eni_types.setdefault(v, {})
            t = e.get("InterfaceType", "interface")
            eni_types[v][t] = eni_types[v].get(t, 0) + 1
            # VPN servers: keyed off a RUNNING INSTANCE, not a security group.
            # Corrected 2026-09-01 -- the earlier group-name heuristic reported VPN
            # presence in an account that has only leftover OpenVPN groups and no
            # server at all, and matched an unrelated group whose *description*
            # happened to mention VPN. An instance either exists or it does not.
            inst = (e.get("Attachment") or {}).get("InstanceId")
            if not inst:
                continue
            if any("openvpn" in (g.get("GroupName") or "").lower() for g in e.get("Groups", [])):
                vpn_by_vpc.setdefault(v, []).append(
                    {"instance": inst, "public": bool(e.get("Association")),
                     "subnet": e.get("SubnetId")})

        flow = {f.get("ResourceId"): f for f in fls}
        nacl_filters = {}
        for n in acls:
            real = [x for x in n.get("Entries", []) if x.get("RuleNumber") != 32767]
            nacl_filters[n["VpcId"]] = not all(
                x.get("RuleAction") == "allow"
                and (x.get("CidrBlock") in ("0.0.0.0/0", None))
                and (x.get("Ipv6CidrBlock") in ("::/0", None)) for x in real)

        ep_by_vpc, tgw_by_vpc = {}, {}
        for x in eps:
            ep_by_vpc.setdefault(x.get("VpcId"), []).append(
                {"id": x.get("VpcEndpointId"), "service": x.get("ServiceName", "").split(".")[-1],
                 "type": x.get("VpcEndpointType")})
        for x in tgws:
            if x.get("ResourceType") == "vpc":
                tgw_by_vpc.setdefault(x.get("ResourceId"), []).append(
                    {"id": x.get("TransitGatewayAttachmentId"), "tgw": x.get("TransitGatewayId"),
                     "state": x.get("State")})

        acct = by_profile.setdefault(prof, {
            "profile": prof, "id": prof_to_acct.get(prof, ""),
            "name": org.get(prof_to_acct.get(prof, ""), ""), "vpcs": []})

        for v in vpcs:
            vid = v["VpcId"]
            tiers = {}
            for s in subs:
                if s["VpcId"] != vid:
                    continue
                rt = explicit.get(s["SubnetId"]) or main.get(vid)
                tiers.setdefault(subnet_tier(rt), []).append(s["CidrBlock"])
            for k in tiers:
                tiers[k].sort()

            ingress, egress = [], []
            for sg in sgs:
                if sg.get("VpcId") != vid:
                    continue
                attached = lb_by_sg.get(sg["GroupId"], [])
                scheme = ("internet-facing" if any(l.get("Scheme") == "internet-facing" for l in attached)
                          else ("internal" if attached else "not on a load balancer"))
                for r in _open_rules(sg, "ingress"):
                    if not r["services"]:
                        continue
                    ingress.append({"sg": sg["GroupId"], "name": sg.get("GroupName", ""),
                                    "port": r["port"], "services": r["services"],
                                    "scheme": scheme,
                                    "lbs": [l["LoadBalancerName"] for l in attached]})
                for r in _open_rules(sg, "egress"):
                    if r["all"]:
                        egress.append({"sg": sg["GroupId"], "name": sg.get("GroupName", ""),
                                       "port": r["port"]})

            acct["vpcs"].append({
                "region": region, "id": vid, "cidr": v["CidrBlock"],
                "default": bool(v.get("IsDefault")),
                "name": _tag(v.get("Tags")) or ("default VPC" if v.get("IsDefault") else vid),
                "tiers": tiers, "enis": eni_count.get(vid, 0), "eni_types": eni_types.get(vid, {}),
                "flowlog": flow.get(vid), "nacl_filters": nacl_filters.get(vid, False),
                "exposures": ingress, "egress_all": egress,
                "endpoints": ep_by_vpc.get(vid, []), "tgw": tgw_by_vpc.get(vid, []),
                "vpn": vpn_by_vpc.get(vid, []),
            })

        for x in d.load(prof, region, "peer").get("VpcPeeringConnections", []):
            model["peerings"].append({
                "id": x.get("VpcPeeringConnectionId"), "region": region,
                "name": _tag(x.get("Tags")) or "(untagged)",
                "state": x.get("Status", {}).get("Code"),
                "a_owner": x.get("RequesterVpcInfo", {}).get("OwnerId"),
                "a_vpc": x.get("RequesterVpcInfo", {}).get("VpcId"),
                "a_cidr": x.get("RequesterVpcInfo", {}).get("CidrBlock"),
                "b_owner": x.get("AccepterVpcInfo", {}).get("OwnerId"),
                "b_vpc": x.get("AccepterVpcInfo", {}).get("VpcId"),
                "b_cidr": x.get("AccepterVpcInfo", {}).get("CidrBlock"),
            })

    known = set(prof_to_acct.values())
    seen, deduped = set(), []
    for p in model["peerings"]:
        if p["id"] in seen:
            continue
        seen.add(p["id"])
        p["external"] = (p["a_owner"] not in known) or (p["b_owner"] not in known)
        deduped.append(p)
    model["peerings"] = deduped
    model["accounts"] = sorted(by_profile.values(), key=lambda a: a["profile"])
    return model


if __name__ == "__main__":
    import sys
    m = build(sys.argv[1])
    p = m["provenance"]
    print(f"collected {p['collected_utc']} by {p['collected_by']}")
    print(f"digest {p['digest']}  files {p['files']}")
    print(f"regions enabled {len(m['regions_enabled'])}, with VPCs: {', '.join(m['regions_with_vpcs'])}")
    print(f"org accounts {m['org_account_count']}, uncovered {len(m['uncovered_accounts'])}")
    for a in m["accounts"]:
        for v in a["vpcs"]:
            print(f"  {a['profile']:<16} {v['region']:<15} {v['name'][:24]:<24} {v['cidr']:<16} "
                  f"enis={v['enis']:<4} ing={len(v['exposures'])} eg={len(v['egress_all'])} "
                  f"ep={len(v['endpoints'])} tgw={len(v['tgw'])}")
    print(f"peerings {len(m['peerings'])}")
